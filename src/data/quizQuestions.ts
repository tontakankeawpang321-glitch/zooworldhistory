// Helper function to generate and shuffle 100 question list
export function getShuffledQuizQuestions(count: number = 10, customKnowledgeItems: KnowledgeItem[] = []): QuizQuestion[] {
  let combinedBank: QuizQuestion[] = [...QUIZ_BANK_100];

  // Dynamically turn fetched KnowledgeItems into questions if available
  if (customKnowledgeItems && customKnowledgeItems.length > 0) {
    customKnowledgeItems.forEach((item, idx) => {
      if (item.title && item.description) {
        combinedBank.push({
          id: `dyn_k_${idx}`,
          question: `เกี่ยวกับเรื่อง "${item.title}" ข้อใดกล่าวถูกต้องตามสารานุกรมสัตว์โลก?`,
          options: [
            item.description.slice(0, 70),
            "เป็นสัตว์ทะเลลึกที่สูญพันธุ์ไปแล้วเมื่อ 500 ปีก่อน",
            "พบอาศัยอยู่เฉพาะในแถบขั้วโลกเหนือเท่านั้น",
            "จัดเป็นพืชป่าชายเลนชนิดหนึ่งที่ไม่มีการเคลื่อนที่"
          ],
          correctAnswerIndex: 0,
          explanation: `${item.title}: ${item.description}`,
          category: item.category || "ความรู้สัตว์โลก"
        });
      }
    });
  }

  // Shuffle combined array (Fisher-Yates)
  const shuffled = [...combinedBank];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  // Also shuffle options for each selected question so answer is not always A
  return shuffled.slice(0, count).map((q, qIndex) => {
    const originalCorrectOption = q.options[q.correctAnswerIndex];
    const shuffledOptions = [...q.options];
    
    for (let i = shuffledOptions.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [shuffledOptions[i], shuffledOptions[j]] = [shuffledOptions[j], shuffledOptions[i]];
    }

    const newCorrectIndex = shuffledOptions.indexOf(originalCorrectOption);

    return {
      ...q,
      id: `q_shuffled_${qIndex}_${Date.now()}`,
      options: shuffledOptions,
      correctAnswerIndex: newCorrectIndex >= 0 ? newCorrectIndex : 0
    };
  });
}
